"""Render ``docs/evaluation.md`` from a results file (Phase 3 plan §7). Deterministic: same results, same bytes."""

from __future__ import annotations

from food_concierge.evaluation.results import PRIMARY, CandidateResult, RetrievalResults, Stat

METRICS = ("ndcg@3", "success@3", "recall@3", "recall@10", "mrr", "violation@3", "judged@3", "empty")
LABELS = {
    "ndcg@3": "nDCG@3",
    "success@3": "Success@3",
    "recall@3": "Recall@3",
    "recall@10": "Recall@10",
    "mrr": "MRR",
    "violation@3": "Violation@3",
    "judged@3": "judged@3",
    "empty": "empty",
}


def _cell(stat: Stat | None) -> str:
    return "—" if stat is None else f"{stat.mean:.3f} [{stat.low:.3f}, {stat.high:.3f}]"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def _candidates(candidates: tuple[CandidateResult, ...]) -> list[str]:
    shown = [m for m in METRICS if any(m in c.summary for c in candidates)]
    rows = [[c.name] + [_cell(c.summary.get(m)) for m in shown] for c in candidates]
    return _table(["Candidate"] + [LABELS[m] for m in shown], rows)


def _slices(candidates: tuple[CandidateResult, ...]) -> list[str]:
    metric = PRIMARY if any(PRIMARY in c.summary for c in candidates) else "violation@3"
    keys = sorted({key for c in candidates for key in c.slices})
    rows = [[c.name] + [_cell(c.slices.get(key, {}).get(metric)) for key in keys] for c in candidates]
    return [f"{LABELS[metric]} by slice.", "", *_table(["Candidate", *keys], rows)]


def render_report(results: RetrievalResults) -> str:
    record = results.record
    machine = record.machine
    lines = [
        "# Retrieval evaluation",
        "",
        "Generated by `python -m food_concierge.flows report` from the committed results; do not edit by hand.",
        "",
        f"- **Split:** {results.split}" + (" (queries not split yet)" if results.split == "all" else ""),
        f"- **Commit:** `{record.git_sha[:12]}`, run {record.created_at:%Y-%m-%d}",
        f"- **Catalog data:** `{record.data_sha256[:12]}`; **queries:** `{results.queries_sha256[:12]}`",
        f"- **Seed:** {record.seeds['eval_seed']}; **machine:** {machine.cpu}, {machine.cores} cores, {machine.os}",
        "",
        "Each cell is the mean with its 95% percentile-bootstrap interval over queries (10,000 seeded "
        "resamples; the ladder deltas are paired). A metric a query cannot define is left out, not zeroed, so"
        " `—` means no query defines it yet (nDCG@3 and Success@3 need the owner's grades). C0 is the "
        "original approach re-implemented; Violation@3 is judged against the reviewed allergens.",
        "",
        "## Candidates",
        "",
        *_candidates(results.candidates),
        "",
        "## Slices",
        "",
        *_slices(results.candidates),
        "",
        "## Ladder comparisons",
        "",
    ]
    if results.comparisons:
        rows = [
            [f"{c.candidate} vs {c.baseline}", LABELS[c.metric], _cell(c.delta), str(c.delta.n)]
            for c in results.comparisons
        ]
        lines += _table(["Step", "Metric", "Δ (candidate - baseline)", "Queries"], rows)
    else:
        lines.append("None yet: comparisons are on nDCG@3, which needs the owner's grades.")
    lines += ["", "## Gate", ""]
    if results.gate.passed:
        lines.append("Passed.")
    else:
        lines += [f"- {failure}" for failure in results.gate.failures]
    lines += [
        "",
        "## Not in this run",
        "",
        "- **Latency:** measured with the real models for ADR-0001, since cached models only look scores up.",
        "- **Image ladder (L0-L2):** added once the image-query descriptions are complete.",
        "- **κ:** added once the owner's re-graded sample exists.",
    ]
    return "\n".join(lines) + "\n"
